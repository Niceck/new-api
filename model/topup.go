// decimalQuotaForAmount 把易支付口径的美元数量换算成额度。
// 易支付订单的 Amount 是美元数量，额度 = Amount * QuotaPerUnit。
func decimalQuotaForAmount(amount int64) int64 {
	return decimal.NewFromInt(amount).Mul(decimal.NewFromFloat(common.QuotaPerUnit)).IntPart()
}

// RechargeEpay 完成易支付订单并入账，订单状态与用户额度在同一事务内落库。
//
// 返回本次实际入账的额度：重投（订单已 success）返回 0，便于调用方区分
// 「首次入账」与「幂等重投」而不必再查库。
//
// 为什么必须是事务：webhook 只有一次交付机会——平台收到 success 应答后不再重投。
// 若订单先标成功、额度另起一个事务再加，中间失败就变成「订单成功但没到账」
// （reconcile_topup.py 的形态 B），只能靠人工补单。与 Recharge(Stripe)、
// RechargeCreem 同构：行级锁 + 幂等判定 + 行内 quota + ?。
func RechargeEpay(tradeNo string, actualPaymentMethod string, paidMoney string, callerIp string) (creditedQuota int, err error) {
	if tradeNo == "" {
		return 0, errors.New("未提供支付单号")
	}

	refCol := "`trade_no`"
	if common.UsingMainDatabase(common.DatabaseTypePostgreSQL) {
		refCol = `"trade_no"`
	}

	var userId int
	var payMoney float64
	var storedPaymentMethod string

	err = DB.Transaction(func(tx *gorm.DB) error {
		topUp := &TopUp{}
		// 行级锁：并发回调与管理员补单串行化，避免双重入账。
		if err := lockForUpdate(tx).Where(refCol+" = ?", tradeNo).First(topUp).Error; err != nil {
			// 只有「查无此行」才是订单不存在。断连、行锁等待超时这类查询故障要原样
			// 返回：调用方对「订单不存在」回 success、平台不再重投，把故障报成它，
			// 这笔已付款的订单就再也入不了账。
			if errors.Is(err, gorm.ErrRecordNotFound) {
				return ErrTopUpNotFound
			}
			return err
		}
		// provider 隔离：TRON 等独立网关有自己的结算路径，不得在此处理。
		if topUp.PaymentProvider != PaymentProviderEpay {
			return ErrPaymentMethodMismatch
		}
		// 幂等：平台重投时订单已 success，直接返回且不再入账。
		if topUp.Status == common.TopUpStatusSuccess {
			creditedQuota = 0
			return nil
		}
		if topUp.Status != common.TopUpStatusPending {
			return ErrTopUpStatusInvalid
		}
		// 金额比对：验签只证明通知出自持有商户密钥的一方，额度却按本地订单的
		// Amount 入账——金额更小却指向这张订单的通知一旦放行，就是花小钱拿大额度。
		// 不符就不入账，订单留在 pending，交给对账巡检与人工核实。
		if !epayAmountMatches(topUp.Money, paidMoney) {
			return fmt.Errorf("%w: order_money=%s callback_money=%q",
				ErrTopUpAmountMismatch, EpayOrderMoney(topUp.Money), paidMoney)
		}

		quotaToAdd := decimalQuotaForAmount(topUp.Amount)
		if quotaToAdd <= 0 || quotaToAdd > int64(common.MaxQuota) {
			return errors.New("无效的充值额度")
		}

		// 钱包上限：先读当前额度再判断，越界则整单回滚而不是部分入账。
		user := &User{}
		if err := lockForUpdate(tx).Select("id", "quota").Where("id = ?", topUp.UserId).First(user).Error; err != nil {
			return err
		}
		if int64(user.Quota) > int64(common.MaxQuota)-quotaToAdd {
			return errors.New("充值后额度超出上限，请联系管理员")
		}

		// 实际支付方式可能与下单时不同，落库记实际值。
		if actualPaymentMethod != "" && topUp.PaymentMethod != actualPaymentMethod {
			topUp.PaymentMethod = actualPaymentMethod
		}
		topUp.CompleteTime = common.GetTimestamp()
		topUp.Status = common.TopUpStatusSuccess
		if err := tx.Save(topUp).Error; err != nil {
			return err
		}

		if err := tx.Model(&User{}).Where("id = ?", topUp.UserId).
			Update("quota", gorm.Expr("quota + ?", quotaToAdd)).Error; err != nil {
			return err
		}

		creditedQuota = int(quotaToAdd)
		userId = topUp.UserId
		payMoney = topUp.Money
		storedPaymentMethod = topUp.PaymentMethod
		return nil
	})
	if err != nil {
		return 0, err
	}

	if creditedQuota > 0 {
		// 缓存与日志都放在提交之后：事务未提交就刷缓存会让失败回滚留下脏额度。
		if common.RedisEnabled {
			if cacheErr := cacheIncrUserQuota(userId, int64(creditedQuota)); cacheErr != nil {
				common.SysError("failed to increase cached user quota after epay topup: " + cacheErr.Error())
			}
		}
		RecordTopupLog(userId, fmt.Sprintf("使用在线充值成功，充值金额: %v，支付金额：%f", logger.FormatQuota(creditedQuota), payMoney), callerIp, storedPaymentMethod, PaymentProviderEpay)
	}
	return creditedQuota, nil
}

// ManualCompleteTopUp 管理员手动完成订单并给用户充值
func ManualCompleteTopUp(tradeNo string, callerIp string) error {
	if tradeNo == "" {
		return errors.New("未提供订单号")
	}

	refCol := "`trade_no`"
	if common.UsingMainDatabase(common.DatabaseTypePostgreSQL) {
		refCol = `"trade_no"`
	}

	var userId int
	var quotaToAdd int
	var payMoney float64
	var paymentMethod string

	err := DB.Transaction(func(tx *gorm.DB) error {
		topUp := &TopUp{}
		// 行级锁，避免并发补单
		if err := lockForUpdate(tx).Where(refCol+" = ?", tradeNo).First(topUp).Error; err != nil {
			return errors.New("充值订单不存在")
		}
		if topUp.PaymentProvider == PaymentProviderTron {
			return ErrPaymentMethodMismatch
		}

		// 幂等处理：已成功直接返回
		if topUp.Status == common.TopUpStatusSuccess {
			return nil
		}

		if topUp.Status != common.TopUpStatusPending {
			return errors.New("订单状态不是待支付，无法补单")
		}

		// 应充值额度与各渠道回调入账同一口径（topUpCreditQuota）：Stripe 按 Money，
		// Creem 的 Amount 本身就是额度，其余按 Amount * QuotaPerUnit。它先比较再转整数，
		// 数量离谱的订单不会在转换时绕回成一个看似正常的值。
		credit := topUpCreditQuota(topUp)
		if credit <= 0 || credit > int64(common.MaxQuota) {
			return errors.New("无效的充值额度")
		}
		quotaToAdd = int(credit)

		// 钱包上限：与回调入账（RechargeEpay）同一道检查。补到上限以外的话，这个用户
		// 之后的每一笔充值都会在入账环节被拒，付了款却卡在待处理。
		user := &User{}
		if err := lockForUpdate(tx).Select("id", "quota").Where("id = ?", topUp.UserId).First(user).Error; err != nil {
			return err
		}
		if int64(user.Quota) > int64(common.MaxQuota)-int64(quotaToAdd) {
			return errors.New("补单后额度超出钱包上限：等用户用掉一部分余额后再补，或走退款")
		}

		// 标记完成
		topUp.CompleteTime = common.GetTimestamp()
		topUp.Status = common.TopUpStatusSuccess
		if err := tx.Save(topUp).Error; err != nil {
			return err
		}

		// 增加用户额度（立即写库，保持一致性）
		if err := tx.Model(&User{}).Where("id = ?", topUp.UserId).Update("quota", gorm.Expr("quota + ?", quotaToAdd)).Error; err != nil {
			return err
		}

		userId = topUp.UserId
		payMoney = topUp.Money
		paymentMethod = topUp.PaymentMethod
		return nil
	})

	if err != nil {
		return err
	}

	// 事务外记录日志，避免阻塞
	RecordTopupLog(userId, fmt.Sprintf("管理员补单成功，充值金额: %v，支付金额：%f", logger.FormatQuota(quotaToAdd), payMoney), callerIp, paymentMethod, "admin")
	return nil
}
func RechargeCreem(referenceId string, customerEmail string, customerName string, callerIp string) (err error) {
	if referenceId == "" {
		return errors.New("未提供支付单号")
	}

	var quota int64
	topUp := &TopUp{}

	refCol := "`trade_no`"
	if common.UsingMainDatabase(common.DatabaseTypePostgreSQL) {
		refCol = `"trade_no"`
	}

	err = DB.Transaction(func(tx *gorm.DB) error {
		err := lockForUpdate(tx).Where(refCol+" = ?", referenceId).First(topUp).Error
		if err != nil {
			return errors.New("充值订单不存在")
		}

		if topUp.PaymentProvider != PaymentProviderCreem {
			return ErrPaymentMethodMismatch
		}

		if topUp.Status != common.TopUpStatusPending {
			return errors.New("充值订单状态错误")
		}

		topUp.CompleteTime = common.GetTimestamp()
		topUp.Status = common.TopUpStatusSuccess
		err = tx.Save(topUp).Error
		if err != nil {
			return err
		}

		// Creem 直接使用 Amount 作为充值额度（整数）
		quota = topUp.Amount

		// 构建更新字段，优先使用邮箱，如果邮箱为空则使用用户名
		updateFields := map[string]interface{}{
			"quota": gorm.Expr("quota + ?", quota),
		}

		// 如果有客户邮箱，尝试更新用户邮箱（仅当用户邮箱为空时）
		if customerEmail != "" {
			// 先检查用户当前邮箱是否为空
			var user User
			err = tx.Where("id = ?", topUp.UserId).First(&user).Error
			if err != nil {
				return err
			}

			// 如果用户邮箱为空，则更新为支付时使用的邮箱
			if user.Email == "" {
				updateFields["email"] = customerEmail
			}
		}

		err = tx.Model(&User{}).Where("id = ?", topUp.UserId).Updates(updateFields).Error
		if err != nil {
			return err
		}

		return nil
	})

	if err != nil {
		common.SysError("creem topup failed: " + err.Error())
		return errors.New("充值失败，请稍后重试")
	}

	RecordTopupLog(topUp.UserId, fmt.Sprintf("使用Creem充值成功，充值额度: %v，支付金额：%.2f", quota, topUp.Money), callerIp, topUp.PaymentMethod, PaymentMethodCreem)

	return nil
}

